/**
 * P6 S1 (C0e): one row per route of the server, read by test/p6-route-matrix.test.ts. Rows come from
 * phase6 research-C2-routes.md (routes at Phase 4) and recheck-S1-routes.md (Phase 5 routes), plus the
 * routes S1's C0 registers (projects, sharing, transfer, roles, security settings, L8's project vaults).
 *
 * - `path` is the full path as Fastify registers it: `/rest/...` for the editor API, `/api/v1/...` for the
 *   public API (called with an API key), root paths for webhooks, forms, MCP, health and widgets.
 * - `method` `ALL` is a route registered for every method (webhooks); a route registered for a few methods
 *   has one row for the method it serves (the MCP server's POST).
 * - `scope` is the scope the route checks (for a route that takes either of two scopes, the first one;
 *   owner/admin hold both and editor/viewer neither, so allow and deny are the same). `null` is a route
 *   with no scope: `access: 'public'` needs no session, `access: 'auth'` any signed-in user, and a `null`
 *   row with no `access` is a role-only gate that `legacyMin` names (DELETE /tenant, owner only).
 * - `target` is the row `:id` stands for (the other path params are filled by their names), so a refused
 *   role meets a real row and answers 403, not 404.
 * - `legacyMin` was the minimum role of the old model (`requireRole`), pinned until the cutover (P6-39): it is
 *   read by nothing now and later stages write rows without it. `change` notes a rule that differs from the old
 *   model on purpose.
 * - `exactScopes` names every scope a custom role needs for the row when the route checks more than `scope`.
 * - `check` says where the route checks the scope when that is not the row's target: `personal` (a create
 *   with no project goes to the caller's personal project) or `global` (the workspace role's scopes).
 * - `stream: true` rows answer an open stream (SSE, the AI builder, MCP): the test reads their status through
 *   a real listener and aborts.
 *
 * After C0 only L13 edits this file (its public rows: `/folders` gone for `/projects/:projectId/folders`, the
 * new project, role, transfer and security policy rows, the unfiltered list rows as `scope: null`); L24 edits it last. Later stages
 * add one row per new route in their own C0.
 */
