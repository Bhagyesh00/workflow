export function isCodeLanguage(value: string): value is CodeLanguage {
  return (CODE_LANGUAGES as readonly string[]).includes(value);
}

export function codeSeparators(language: string): string[] {
  if (!isCodeLanguage(language)) throw new Error(`Unknown code language: ${language}`);
  return [...SEPARATORS[language]];
}
